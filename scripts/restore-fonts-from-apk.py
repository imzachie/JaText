#!/usr/bin/env python3
"""
Recovers the real SF Pro subsets and the iOS colour emoji font out of a built
release APK and drops them into android/app/src/main/res/font/.

Why this exists: those files were generated by scripts/fetch-sf-pro-fonts.py
from a separate asset repository, and when that repo went away the APK build
started failing on a font. Everything the build needs is already inside the last
released APK, so this reads it back out. Resource paths are shortened during
packaging (res/-c.otf and friends), so each font is identified by its own tables
rather than by its file name.

    python3 scripts/restore-fonts-from-apk.py release-cdn/JaText-release.apk
"""

from __future__ import annotations

import io
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR = REPO_ROOT / "scripts" / "fetch-sf-pro-fonts.py"

MIN_OTF_BYTES = 50_000
MIN_EMOJI_BYTES = 4_000_000


def load_manifest() -> tuple[list[tuple[str, int, bool]], str]:
    """Read the expected font list out of the fetcher, which owns it.

    That file has dashes in its name so it cannot be imported the usual way,
    and duplicating the list here would let the two drift apart.
    """
    import importlib.util

    spec = importlib.util.spec_from_file_location("jatext_font_fetcher", GENERATOR)
    if spec is None or spec.loader is None:
        raise SystemExit(f"Cannot load {GENERATOR}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    entries = [
        (res_name, int(weight), bool(italic))
        for res_name, _remote, _sha, weight, italic in module.SF_PRO_FONT_MANIFEST
    ]
    return entries, module.IOS_EMOJI_RES_NAME


FONT_MANIFEST, EMOJI_RES_NAME = load_manifest()





WEIGHT_TOKENS = {
    100: "ultralight",
    200: "thin",
    300: "light",
    400: "regular",
    500: "medium",
    600: "semibold",
    700: "bold",
    800: "heavy",
    900: "black",
}


def expected_key(res_name: str, weight: int, italic: bool) -> str:
    """The PostScript name one manifest entry should produce.

    sf_pro_text_semibold_italic -> sfprotext-semibolditalic
    """
    bucket = "rounded" if "rounded" in res_name else "display" if "display" in res_name else "text"
    token = WEIGHT_TOKENS.get(int(weight))
    if token is None:
        return ""
    suffix = "%s%s" % (token, "italic" if italic else "")
    # The comparison side strips separators, so this side has to as well.
    return "sfpro%s%s" % (bucket, suffix)


def actual_key(blob: bytes) -> str:
    """The PostScript name of a font as a comparable lower case slug.

    Weight plus italic alone is not enough to identify a font: CFF italics do
    not always report the italic flag, so matching on that silently pairs an
    italic face with a regular name. The PostScript name is exact.
    """
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        raise SystemExit("fonttools is required: python3 -m pip install fonttools")
    try:
        font = TTFont(io.BytesIO(blob), fontNumber=0, lazy=True)
    except Exception:
        return ""
    name = ""
    if "name" in font:
        names = font["name"]
        name = str(names.getDebugName(6) or names.getDebugName(4) or "")
    font.close()
    return "".join(ch for ch in name.lower() if ch.isalnum())


def extract(apk_path: Path, out_dir: Path) -> int:
    with zipfile.ZipFile(apk_path) as zf:
        entries = [i for i in zf.infolist() if i.filename.startswith("res/")]
        otf_entries = [i for i in entries if i.filename.endswith(".otf")]
        ttf_entries = [
            i for i in entries if i.filename.endswith(".ttf") and i.file_size >= MIN_EMOJI_BYTES
        ]
        if not otf_entries:
            raise SystemExit(f"No .otf resources found inside {apk_path}.")

        by_manifest: dict[str, bytes] = {}
        wanted = {
            expected_key(res_name, weight, italic): res_name
            for res_name, weight, italic in FONT_MANIFEST
        }
        leftovers: list[str] = []
        for info in otf_entries:
            blob = zf.read(info.filename)
            if len(blob) < MIN_OTF_BYTES or blob[:4] != b"OTTO":
                continue
            key = actual_key(blob)
            res_name = wanted.get(key)
            if res_name and res_name not in by_manifest:
                by_manifest[res_name] = blob
            else:
                leftovers.append(f"{info.filename} ({key or 'unreadable'})")
        if leftovers:
            print(
                f"  note: {len(leftovers)} font(s) in the APK had no manifest entry: "
                + ", ".join(leftovers[:6])
            )

        out_dir.mkdir(parents=True, exist_ok=True)
        written = 0
        for res_name, _w, _i in FONT_MANIFEST:
            blob = by_manifest.get(res_name)
            if blob is None:
                print(f"  ! {res_name}: not found in the APK")
                continue
            (out_dir / f"{res_name}.otf").write_bytes(blob)
            written += 1

        emoji_blob = None
        for info in ttf_entries:
            blob = zf.read(info.filename)
            if b"CBDT" in blob[:512] and b"CBLC" in blob[:512]:
                emoji_blob = blob
                break
        if emoji_blob is not None:
            (out_dir / f"{EMOJI_RES_NAME}.ttf").write_bytes(emoji_blob)
            written += 1
        else:
            print(f"  ! {EMOJI_RES_NAME}.ttf: no CBDT/CBLC colour font in the APK")

    return written


def already_real(out_dir: Path) -> bool:
    if not out_dir.exists():
        return False
    for res_name, _w, _i in FONT_MANIFEST:
        candidate = out_dir / f"{res_name}.otf"
        if not candidate.exists() or candidate.stat().st_size < MIN_OTF_BYTES:
            return False
    emoji = out_dir / f"{EMOJI_RES_NAME}.ttf"
    return emoji.exists() and emoji.stat().st_size >= MIN_EMOJI_BYTES


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    apk_path = Path(args[0]) if args else REPO_ROOT / "release-cdn" / "JaText-release.apk"
    out_dir = REPO_ROOT / "android" / "app" / "src" / "main" / "res" / "font"

    if not apk_path.exists():
        raise SystemExit(f"APK not found: {apk_path}")
    if "--check" in sys.argv:
        print("fonts are real and committed" if already_real(out_dir) else "fonts are missing or stubs")
        return
    if "--skip-if-present" in sys.argv and already_real(out_dir):
        print(f"{out_dir} already holds the real fonts, nothing to restore.")
        return

    with tempfile.TemporaryDirectory() as tmp:
        _ = Path(tmp)
        count = extract(apk_path, out_dir)
    total = sum(f.stat().st_size for f in out_dir.iterdir())
    print(
        f"Restored {count} font files into {out_dir} "
        f"({total / (1024 * 1024):.2f} MiB) from {apk_path.name}."
    )
    if shutil.which("git"):
        subprocess.run(
            ["git", "add", "-A", str(out_dir.relative_to(REPO_ROOT))],
            cwd=REPO_ROOT,
            check=False,
        )


if __name__ == "__main__":
    main()
