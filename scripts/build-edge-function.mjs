#!/usr/bin/env node
/**
 * Bundles the Supabase Edge Function from supabase/functions-src into
 * supabase/functions, ready for `supabase functions deploy`.
 *
 * A Supabase function can only import files that were uploaded with it, so the
 * backend has to be flattened into one artifact. esbuild does that job here, at
 * build time, which keeps a laptop out of the picture: committing the output is
 * what makes `supabase functions deploy --use-workdir` (or a dashboard upload)
 * possible with no local toolchain.
 *
 * Run: node scripts/build-edge-function.mjs
 */
import { build } from "esbuild";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = path.join(root, "supabase/functions-src/jatext-api/index.ts");
const OUT_DIR = path.join(root, "supabase/functions/jatext-api");

// esbuild only accepts literal strings here, so the Node builtins Deno resolves
// itself are listed out; a wildcard would silently bundle a shim instead.
const externals = [
  "node:buffer",
  "node:crypto",
  "node:fs",
  "node:fs/promises",
  "node:http",
  "node:path",
  "node:process",
  "node:url",
  "node:util",
  // Only reachable through branches a Supabase deploy never takes: an Edge
  // runtime has no libsql native client.
  "@libsql/client",
  "@libsql/client/web",
  // The Edge build's `pg` is imported through this exact npm: specifier by
  // server/pgDenoDriver.js; esbuild cannot resolve it and neither should it try.
  "npm:pg@8.23.1",
];

async function main() {
  const result = await build({
    entryPoints: [ENTRY],
    outfile: path.join(OUT_DIR, "index.ts"),
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "esnext",
    logLevel: "warning",
    external: externals,
    // Deno decides what to ship while it bundles, not while code runs, so a lazy
    // import("npm:pg@…") fails in a deployed function with "Could not find
    // constraint 'pg' in the list of packages". Swapping the bare specifier for a
    // module that imports it statically puts the driver inside the deployment,
    // while Node keeps resolving plain "pg" from node_modules.
    alias: { pg: path.resolve(root, "server/pgDenoDriver.js") },
    // The dynamic route imports in the host become inline promises once
    // bundled; keeping them lazy preserves cold-start behaviour.
    splitting: false,
    legalComments: "none",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (result.errors?.length) {
    for (const err of result.errors) console.error(err.text);
    process.exit(1);
  }

  const file = path.join(OUT_DIR, "index.ts");
  let code = await readFile(file, "utf8");
  // Nothing may be left for the edge runtime to look up by bare package name:
  // Deno resolves Node builtins itself and resolves npm:/jsr: specifiers while it
  // bundles the deployment, but a plain "pg" in the output would sit unresolved
  // until a request hit it. Every optional dependency therefore has to stay
  // behind a computed specifier, and the Postgres driver has to be inside the
  // bundle for real.
  const banned = [
    /^import[^\n]*?from\s+["'](?!node:|npm:|jsr:|\.)([^"']+)["']/m,
    /^export[^\n]*?from\s+["'](?!node:|npm:|jsr:|\.)([^"']+)["']/m,
  ];
  for (const re of banned) {
    const hit = code.match(re);
    if (hit) {
      console.error(`build left an unresolvable static import in the bundle: ${hit[0].slice(0, 120)}`);
      process.exit(1);
    }
  }
  // The driver must be provably shipped, not fetched on first use: a lazy import of
  // an npm package is what made the deployed function answer
  // "Could not find constraint 'pg' in the list of packages".
  if (!/^import[^\n]*?from\s+["']npm:pg@/m.test(code)) {
    console.error(
      "bundle does not import the Postgres driver statically via npm:pg, so the " +
        "deployed function would not be able to load it at runtime",
    );
    process.exit(1);
  }

  code = code.replace(
    /^/,
    "// Generated by scripts/build-edge-function.mjs - do not edit.\n" +
      "// Edit supabase/functions-src/jatext-api/index.ts or server/*.js instead.\n",
  );
  await writeFile(file, code);
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(
    path.join(OUT_DIR, "README.md"),
    "Generated. Edit `supabase/functions-src/jatext-api/index.ts`, then run `node scripts/build-edge-function.mjs`.\n",
  );
  const kb = (await readFile(file)).length / 1024;
  console.log(`bundled ${path.relative(root, file)} (${kb.toFixed(0)} KB)`);
}

main().catch((err) => {
  console.error(err?.message || err);
  process.exit(1);
});
