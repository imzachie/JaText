#!/usr/bin/env node
/**
 * Prints the SQL `initSchemaOnDb` would run against PostgreSQL.
 *
 * The app creates its own tables on the first request, which is the right default
 * for a self-hosted box. On a Supabase Edge Function a cold start that also has
 * to issue 28 CREATE TABLE statements risks the request time limit, so the schema
 * is worth applying once, ahead of time, from a place with no timeout.
 *
 * Run: node scripts/dump-supabase-schema.mjs > schema.sql
 */
import { initSchemaOnDb } from "../server/tursoBackend.js";
import { translateSqlToPostgres } from "../server/postgresAdapter.js";

const out = [];
const fake = {
  engine: "postgresql",
  async execute(stmt) {
    const sql = typeof stmt === "string" ? stmt : stmt?.sql;
    if (!sql) return { rows: [] };
    out.push(translateSqlToPostgres(sql).trim().replace(/;+$/, "") + ";");
    return { rows: [] };
  },
  async batch(list) {
    for (const stmt of list || []) await fake.execute(stmt);
    return [];
  },
};

await initSchemaOnDb(fake);
console.log("-- JaText schema, generated by scripts/dump-supabase-schema.mjs");
console.log(out.join("\n"));
