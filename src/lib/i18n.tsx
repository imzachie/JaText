const STORAGE_KEY = "jatext:language:v1";
const listeners = new Set<() => void>();

function readInitialLanguage(): AppLanguageCode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as AppLanguageCode | null;
    if (saved && APP_LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch {
    // Ignore storage read failure
  }
  return "en";
}

let currentLanguage: AppLanguageCode =
  typeof window !== "undefined" ? readInitialLanguage() : "en";

function applyHtmlLangAttributes(lang: AppLanguageCode) {
  if (typeof document === "undefined") return;
  const opt = APP_LANGUAGES.find((l) => l.code === lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = opt?.rtl ? "rtl" : "ltr";
}

if (typeof window !== "undefined") {
  applyHtmlLangAttributes(currentLanguage);
}

export function getAppLanguage(): AppLanguageCode {
  return currentLanguage;
}

export function setAppLanguage(next: AppLanguageCode): void {
  if (!APP_LANGUAGES.some((l) => l.code === next)) return;
  currentLanguage = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Ignore
  }
  applyHtmlLangAttributes(next);
  for (const fn of listeners) fn();
}

export function translateKey(key: TranslationKey, lang: AppLanguageCode = currentLanguage): string {
  return TRANSLATIONS[lang]?.[key] ?? EN_DICT[key] ?? key;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  useI18n();
  return <>{children}</>;
}

export function useI18n() {
  const language = useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => currentLanguage,
    () => "en" as AppLanguageCode,
  );
  const option = APP_LANGUAGES.find((l) => l.code === language) ?? APP_LANGUAGES[0];
  return {
    language,
    languageOption: option,
    setLanguage: setAppLanguage,
    t: (key: TranslationKey) => translateKey(key, language),
  };
}
